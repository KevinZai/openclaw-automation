/**
 * Workspace Convention Enforcer — Verifies all workspaces have required files
 *
 * Weekly: checks each workspace for required files (AGENTS, IDENTITY, SOUL, TOOLS, USER, HEARTBEAT, MEMORY.md)
 * Flags missing, empty, or broken-reference files.
 * Report → shared/daily-brief/convention-YYYY-MM-DD.md
 *
 * PM2 cron: Sundays 9am EST (0 14 * * 0 UTC)
 */

const fs = require('fs');
const path = require('path');

const WORKSPACES_DIR = process.env.WORKSPACES_DIR || './workspaces';
const BRIEF_DIR = process.env.BRIEF_DIR || './shared/daily-brief';

const REQUIRED_FILES = ['AGENTS.md', 'IDENTITY.md', 'SOUL.md', 'TOOLS.md', 'USER.md', 'HEARTBEAT.md', 'MEMORY.md'];
const SKIP_WORKSPACES = ['archive', 'guests'];

function checkWorkspace(wsName) {
  const wsDir = path.join(WORKSPACES_DIR, wsName);
  const issues = [];

  for (const file of REQUIRED_FILES) {
    const filePath = path.join(wsDir, file);

    if (!fs.existsSync(filePath)) {
      issues.push({ file, type: 'MISSING', detail: 'File does not exist' });
      continue;
    }

    const stat = fs.statSync(filePath);
    if (stat.size === 0) {
      issues.push({ file, type: 'EMPTY', detail: 'File exists but is 0 bytes' });
      continue;
    }

    // Check for broken references in the file
    try {
      const content = fs.readFileSync(filePath, 'utf8');
      const refPattern = /(?:~\/clawd\/|\/Users\/ai\/clawd\/)([\w\-\/\.]+)/g;
      let match;
      while ((match = refPattern.exec(content)) !== null) {
        const refPath = path.join(process.env.CLAWD_DIR || '.', match[1]);
        if (!fs.existsSync(refPath) && !refPath.includes('YYYY') && !refPath.includes('{')) {
          issues.push({ file, type: 'BROKEN_REF', detail: `References non-existent path: ${match[0]}` });
        }
      }
    } catch {}
  }

  // Check memory directory exists
  const memDir = path.join(wsDir, 'memory');
  if (!fs.existsSync(memDir)) {
    issues.push({ file: 'memory/', type: 'MISSING', detail: 'No memory directory' });
  }

  return issues;
}

function run() {
  const today = new Date().toISOString().split('T')[0];

  let workspaces;
  try {
    workspaces = fs.readdirSync(WORKSPACES_DIR)
      .filter(d => {
        const full = path.join(WORKSPACES_DIR, d);
        return fs.statSync(full).isDirectory() && !d.startsWith('.') && !SKIP_WORKSPACES.includes(d);
      })
      .sort();
  } catch (e) {
    console.error('[convention] Cannot read workspaces dir:', e.message);
    process.exit(1);
  }

  let totalIssues = 0;
  const results = [];

  for (const ws of workspaces) {
    const issues = checkWorkspace(ws);
    totalIssues += issues.length;
    results.push({ workspace: ws, issues });
  }

  // Generate report
  let report = `# Workspace Convention Check — ${today}\n\n`;
  report += `**Workspaces checked:** ${workspaces.length} | **Total issues:** ${totalIssues}\n\n`;

  if (totalIssues === 0) {
    report += `✅ All workspaces conform to conventions. No missing or broken files.\n`;
  } else {
    // Summary table
    report += `## Issues by Workspace\n\n`;
    for (const { workspace, issues } of results) {
      if (issues.length === 0) continue;
      report += `### ${workspace} (${issues.length} issues)\n`;
      for (const issue of issues) {
        const icon = issue.type === 'MISSING' ? '❌' : issue.type === 'EMPTY' ? '⚠️' : '🔗';
        report += `- ${icon} **${issue.file}** — ${issue.type}: ${issue.detail}\n`;
      }
      report += '\n';
    }

    // Passing workspaces
    const passing = results.filter(r => r.issues.length === 0).map(r => r.workspace);
    if (passing.length > 0) {
      report += `## ✅ Passing Workspaces\n${passing.join(', ')}\n`;
    }
  }

  report += `\n---\n*Generated by workspace-convention-check.js on ${new Date().toISOString()}*\n`;

  // Write report
  fs.mkdirSync(BRIEF_DIR, { recursive: true });
  const reportFile = path.join(BRIEF_DIR, `convention-${today}.md`);
  fs.writeFileSync(reportFile, report);

  console.log(`[convention] ${workspaces.length} workspaces, ${totalIssues} issues. Report: ${reportFile}`);
}

run();
